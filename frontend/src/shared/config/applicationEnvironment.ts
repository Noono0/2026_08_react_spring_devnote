/**
 * ============================================================================
 * applicationEnvironment.ts — 환경변수를 검사하고 안전하게 꺼내 쓰는 관문
 * ============================================================================
 *
 * [환경변수가 뭔가요?]
 *   서버 주소처럼 "개발할 때와 배포할 때 값이 달라지는" 설정들이다.
 *   코드에 직접 박아 두면 배포할 때마다 코드를 고쳐야 하니,
 *   `.env` 파일에 따로 적어 두고 코드는 그 값을 읽기만 한다.
 *
 *   Vite에서는 VITE_ 로 시작하는 이름만 브라우저 코드에서 읽을 수 있다.
 *   (그렇지 않으면 DB 비밀번호 같은 게 실수로 브라우저에 노출될 수 있다)
 *
 * [이 파일의 핵심 아이디어 — "빨리 실패하기(fail fast)"]
 *   import.meta.env를 코드 여기저기서 그냥 꺼내 쓰면 어떻게 될까?
 *     - .env에 VITE_API_BASE_URL을 안 적었다 → undefined
 *     - 그러면 요청 주소가 "undefined/documents"가 된다
 *     - 화면은 정상으로 보이는데 API만 이상하게 실패한다
 *     - 원인을 찾느라 한참 헤맨다
 *
 *   그래서 앱이 켜지는 순간 환경변수를 전부 검사하고,
 *   하나라도 잘못됐으면 그 자리에서 앱을 멈추고 정확한 에러를 띄운다.
 *   "나중에 이상하게 실패"하느니 "지금 당장 명확하게 실패"하는 게 훨씬 낫다.
 *
 * [Zod란?]
 *   "이 데이터는 이런 모양이어야 한다"는 규칙을 코드로 적고
 *   실제 값이 그 규칙에 맞는지 실행 중에 검사해 주는 라이브러리다.
 *
 *   ★ TypeScript만으로는 부족한 이유
 *     TypeScript의 타입 검사는 "코드를 작성할 때"만 작동하고,
 *     빌드가 끝나면 전부 사라진다. 실행 중에는 아무 검사도 안 한다.
 *     환경변수, API 응답, localStorage처럼 "바깥에서 들어오는 값"은
 *     실행 시점에 진짜로 검사해야 하고, 그 일을 Zod가 한다.
 */

import { z } from "zod";

/**
 * 환경변수가 지켜야 할 규칙표(스키마).
 * 여기 적힌 항목 중 하나라도 없거나 형식이 틀리면 앱이 시작되지 않는다.
 */
const applicationEnvironmentSchema = z.object({
  // 문자열이면서 길이가 1 이상. 즉 빈 문자열("")도 허용하지 않는다.
  // 서버 주소가 비어 있으면 아무 API도 안 되니 반드시 있어야 한다.
  VITE_API_BASE_URL: z.string().min(1),

  // enum = "이 목록에 있는 값만 허용".
  // "axois" 같은 오타를 앱 시작 시점에 바로 잡아 준다.
  VITE_HTTP_CLIENT: z.enum(["axios", "fetch"]),

  // backend = 진짜 서버 사용 / mock = MSW 가짜 서버 사용
  VITE_DATA_SOURCE: z.enum(["backend", "mock"]),

  VITE_MOCK_SCENARIO: z.string().min(1),

  // regex(정규식)로 형식을 검사한다. `/^\d+$/` 를 뜯어보면:
  //   ^   문자열의 시작
  //   \d  숫자 한 글자 (0~9)
  //   +   앞의 것이 1번 이상 반복
  //   $   문자열의 끝
  // 즉 "처음부터 끝까지 숫자로만 이루어진 문자열"이라는 뜻이다.
  // "12a"나 " 12"는 걸러진다.
  VITE_DEVELOPMENT_MEMBER_ID: z.string().regex(/^\d+$/),

  // ★ boolean이 아니라 문자열 "true"/"false"인 것에 주의!
  //   .env 파일에 적은 값은 무조건 문자열로 들어온다.
  //   그래서 코드에서도 `=== "true"` 처럼 문자열로 비교해야 한다.
  VITE_ENABLE_DEVELOPMENT_MENU: z.enum(["true", "false"]),
});

/**
 * 실제 환경변수를 규칙표로 검사하고, 통과한 값을 내보낸다.
 *
 * `.parse(...)`의 동작:
 *   - 규칙에 맞으면 → 값을 그대로 돌려준다 (타입까지 정확하게 붙여서)
 *   - 규칙에 안 맞으면 → 즉시 에러를 던진다
 *
 * ★ 이 줄은 컴포넌트 안이 아니라 파일 최상단에 있다.
 *   그래서 이 파일을 import하는 순간, 즉 앱이 켜지자마자 검사가 실행된다.
 *   설정이 잘못됐으면 흰 화면과 함께 콘솔에 "어떤 변수가 왜 틀렸는지"가 정확히 뜬다.
 *   무섭게 느껴질 수 있지만, 원인 모를 버그를 몇 시간 쫓는 것보다 백 배 낫다.
 *
 * ★ 보너스: parse가 통과하면 TypeScript도 이 객체의 타입을 정확히 안다.
 *   applicationEnvironment.VITE_HTTP_CLIENT 를 찍으면
 *   "axios" | "fetch" 로 자동완성까지 된다. 검사와 타입을 한 번에 얻는 것이다.
 */
export const applicationEnvironment = applicationEnvironmentSchema.parse(import.meta.env);
